static int jd936x_push_table(struct mipi_dsi_device *dsi,
			     const struct jd936x_init_cmd *table,
			     unsigned int len)
{
	u8 buf[1 + JD936X_MAX_PARAMS];
	unsigned int i;
	int ret;

	for (i = 0; i < len; i++) {
		if (table[i].cmd == REGFLAG_DELAY) {
			mdelay(table[i].len);
			continue;
		}

		buf[0] = table[i].cmd;
		memcpy(&buf[1], table[i].params, table[i].len);

		ret = mipi_dsi_dcs_write_buffer(dsi, buf, table[i].len + 1);
		if (ret < 0) {
			log_debug("%s: command %02x failed: %d\n", __func__,
				  table[i].cmd, ret);
			return ret;
		}
	}

	return 0;
}

static int jd936x_enable_backlight(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct jd936x_priv *priv = dev_get_priv(dev);

	return jd936x_push_table(plat->device, priv->desc->init,
				 priv->desc->init_len);
}

static int jd936x_set_backlight(struct udevice *dev, int percent)
{
	struct jd936x_priv *priv = dev_get_priv(dev);
	int ret;

	if (!priv->backlight)
		return 0;

	ret = backlight_enable(priv->backlight);
	if (ret)
		return log_ret(ret);

	return backlight_set_brightness(priv->backlight, percent);
}

static int jd936x_timings(struct udevice *dev, struct display_timing *timing)
{
	struct jd936x_priv *priv = dev_get_priv(dev);

	memcpy(timing, priv->desc->timing, sizeof(*timing));

	return 0;
}

static int jd936x_of_to_plat(struct udevice *dev)
{
	struct jd936x_priv *priv = dev_get_priv(dev);
	int ret;

	priv->desc = (const struct jd936x_panel_desc *)dev_get_driver_data(dev);
	if (!priv->desc)
		return -EINVAL;

	ret = uclass_get_device_by_phandle(UCLASS_PANEL_BACKLIGHT, dev,
					   "backlight", &priv->backlight);
	if (ret) {
		log_debug("%s: cannot get backlight: ret = %d\n",
			  __func__, ret);
		priv->backlight = NULL;
	}

	ret = device_get_supply_regulator(dev, "vccio-supply", &priv->vccio);
	if (ret) {
		log_debug("%s: cannot get vccio-supply: ret = %d\n",
			  __func__, ret);
		return log_ret(ret);
	}

	ret = device_get_supply_regulator(dev, "vdd-supply", &priv->vdd);
	if (ret) {
		log_debug("%s: cannot get vdd-supply: ret = %d\n",
			  __func__, ret);
		return log_ret(ret);
	}

	ret = device_get_supply_regulator(dev, "vdd2-supply", &priv->vdd2);
	if (ret) {
		log_debug("%s: cannot get vdd2-supply: ret = %d\n",
			  __func__, ret);
		return log_ret(ret);
	}

	ret = gpio_request_by_name(dev, "reset-gpios", 0,
				   &priv->reset_gpio, GPIOD_IS_OUT);
	if (ret) {
		log_debug("%s: cannot decode reset-gpios (%d)\n",
			  __func__, ret);
		return log_ret(ret);
	}

	return 0;
}

static int jd936x_hw_init(struct udevice *dev)
{
	struct jd936x_priv *priv = dev_get_priv(dev);
	int ret;

	ret = regulator_set_enable_if_allowed(priv->vccio, true);
	if (ret)
		return log_ret(ret);

	ret = regulator_set_enable_if_allowed(priv->vdd, true);
	if (ret)
		return log_ret(ret);

	mdelay(10);

	ret = regulator_set_enable_if_allowed(priv->vdd2, true);
	if (ret)
		return log_ret(ret);

	ret = dm_gpio_set_value(&priv->reset_gpio, 0);
	if (ret)
		return log_ret(ret);

	udelay(50);

	ret = dm_gpio_set_value(&priv->reset_gpio, 1);
	if (ret)
		return log_ret(ret);

	udelay(50);

	ret = dm_gpio_set_value(&priv->reset_gpio, 0);
	if (ret)
		return log_ret(ret);

	mdelay(20);

	return jd936x_set_backlight(dev, 100);
}

static int jd936x_probe(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct jd936x_priv *priv = dev_get_priv(dev);
	int ret;

	/* fill characteristics of DSI data link */
	plat->lanes = JD936X_LANES;
	plat->format = MIPI_DSI_FMT_RGB888;
	plat->mode_flags = priv->desc->mode_flags;

	if (plat->device) {
		plat->device->lanes = plat->lanes;
		plat->device->format = plat->format;
		plat->device->mode_flags = plat->mode_flags;

		ret = mipi_dsi_attach(plat->device);
		if (ret)
			return log_ret(ret);
	}

	return jd936x_hw_init(dev);
}

