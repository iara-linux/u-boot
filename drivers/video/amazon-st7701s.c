static int st7701s_push_table(struct mipi_dsi_device *dsi,
			      const struct st7701s_init_cmd *table,
			      unsigned int len)
{
	u8 buf[1 + ST7701S_MAX_PARAMS];
	unsigned int i;
	int ret;

	for (i = 0; i < len; i++) {
		if (table[i].cmd == REGFLAG_DELAY) {
			mdelay(table[i].len);
			continue;
		}

		buf[0] = table[i].cmd;
		memcpy(&buf[1], table[i].params, table[i].len);

		ret = mipi_dsi_dcs_write_buffer(dsi, buf, table[i].len + 1);
		if (ret < 0) {
			log_debug("%s: command %02x failed: %d\n", __func__,
				  table[i].cmd, ret);
			return ret;
		}
	}

	return 0;
}

static int st7701s_enable_backlight(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct st7701s_priv *priv = dev_get_priv(dev);

	return st7701s_push_table(plat->device, priv->desc->init,
				  priv->desc->init_len);
}

static int st7701s_set_backlight(struct udevice *dev, int percent)
{
	struct st7701s_priv *priv = dev_get_priv(dev);
	int ret;

	if (!priv->backlight)
		return 0;

	ret = backlight_enable(priv->backlight);
	if (ret)
		return log_ret(ret);

	return backlight_set_brightness(priv->backlight, percent);
}

static int st7701s_timings(struct udevice *dev, struct display_timing *timing)
{
	struct st7701s_priv *priv = dev_get_priv(dev);

	memcpy(timing, priv->desc->timing, sizeof(*timing));

	return 0;
}

static int st7701s_of_to_plat(struct udevice *dev)
{
	struct st7701s_priv *priv = dev_get_priv(dev);
	int ret;

	priv->desc = (const struct st7701s_panel_desc *)dev_get_driver_data(dev);
	if (!priv->desc)
		return -EINVAL;

	ret = uclass_get_device_by_phandle(UCLASS_PANEL_BACKLIGHT, dev,
					   "backlight", &priv->backlight);
	if (ret) {
		log_debug("%s: cannot get backlight: ret = %d\n",
			  __func__, ret);
		priv->backlight = NULL;
	}

	ret = device_get_supply_regulator(dev, "VCC-supply", &priv->vcc);
	if (ret) {
		log_debug("%s: cannot get VCC-supply: ret = %d\n",
			  __func__, ret);
		return log_ret(ret);
	}

	ret = device_get_supply_regulator(dev, "IOVCC-supply", &priv->iovcc);
	if (ret) {
		log_debug("%s: cannot get IOVCC-supply: ret = %d\n",
			  __func__, ret);
		return log_ret(ret);
	}

	ret = gpio_request_by_name(dev, "reset-gpios", 0,
				   &priv->reset_gpio, GPIOD_IS_OUT);
	if (ret) {
		log_debug("%s: cannot decode reset-gpios (%d)\n",
			  __func__, ret);
		return log_ret(ret);
	}

	return 0;
}

static int st7701s_hw_init(struct udevice *dev)
{
	struct st7701s_priv *priv = dev_get_priv(dev);
	int ret;

	ret = regulator_set_enable_if_allowed(priv->vcc, true);
	if (ret)
		return log_ret(ret);

	ret = regulator_set_enable_if_allowed(priv->iovcc, true);
	if (ret)
		return log_ret(ret);

	ret = dm_gpio_set_value(&priv->reset_gpio, 1);
	if (ret)
		return log_ret(ret);

	mdelay(10);

	ret = dm_gpio_set_value(&priv->reset_gpio, 0);
	if (ret)
		return log_ret(ret);

	mdelay(10);

	ret = dm_gpio_set_value(&priv->reset_gpio, 1);
	if (ret)
		return log_ret(ret);

	mdelay(120);

	return st7701s_set_backlight(dev, 100);
}

static int st7701s_probe(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct st7701s_priv *priv = dev_get_priv(dev);
	int ret;

	/* fill characteristics of DSI data link */
	plat->lanes = ST7701S_LANES;
	plat->format = MIPI_DSI_FMT_RGB888;
	plat->mode_flags = priv->desc->mode_flags;

	if (plat->device) {
		plat->device->lanes = plat->lanes;
		plat->device->format = plat->format;
		plat->device->mode_flags = plat->mode_flags;

		ret = mipi_dsi_attach(plat->device);
		if (ret)
			return log_ret(ret);
	}

	return st7701s_hw_init(dev);
}

